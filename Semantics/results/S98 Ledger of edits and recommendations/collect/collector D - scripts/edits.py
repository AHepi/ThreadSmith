"""Collector D, part 1: the edits of S95 (scrub) and S96 stages 1-3, read from the replacement JSON
files and placed in the line-aligned texts. Returns records; writes nothing."""
import collections, json
from lib import *

S95J = "tests/S95 Scrub - scripts/replacements.json"
S96J1 = "tests/S96 Repair - scripts/replacements.json"
S96J2 = "tests/S96 Repair - scripts/replacements_stage2.json"
S96J3 = "tests/S96 Repair - scripts/replacements_stage3.json"


def run_stage(lines, entries, extra_whole=None):
    """Apply span entries (list of (idx, entry)) line by line; return new lines and per-entry
    (old_sentence, new_sentence)."""
    by_line = collections.defaultdict(list)
    for i, e in entries:
        by_line[e["line"]].append((i, e))
    out = list(lines)
    sent = {}
    spans_of = {}
    for n, es in sorted(by_line.items()):
        orig = lines[n - 1]
        new_line, spans = apply_line(orig, [(e["old"], e["new"], i) for i, e in es])
        out[n - 1] = new_line
        for i, e in es:
            sent[i] = sentences_for(orig, new_line, spans, i)
    if extra_whole:
        for n, para in extra_whole.items():
            out[n - 1] = para
    return out, sent


def base(rid, rnd, src, ref, kind, status, applied_in, ttext, tline, tpart, old, new, os_, ns_, scope):
    return {"rid": rid, "round": rnd, "source_file": src, "source_ref": ref, "kind": kind,
            "status": status, "applied_in": applied_in, "target_text": ttext, "target_line": tline,
            "target_part": tpart, "old": old, "new": new, "old_sentence": os_, "new_sentence": ns_,
            "scope": scope, "same_as": []}


def build(next_rid):
    recs = []
    texts = {k: load_text(k) for k in TEXTS}
    report = {}
    # ---------- S95 ----------
    R = json.load(open(SEM + S95J, encoding="utf-8"))
    d5 = texts["draft 5"]
    H5 = headings(d5)
    ents = list(enumerate(R["entries"]))
    fills = {int(k): v for k, v in R["fill_blank_lines"].items()}
    scr, sent = run_stage(d5, ents, fills)
    report["S95 rebuild md5"] = md5("\n".join(scr))
    report["S95 rebuild equals scrubbed copy"] = scr == texts["scrubbed copy"]
    Hs = headings(texts["scrubbed copy"])
    for i, e in ents:
        n = e["line"]
        orig = d5[n - 1]
        os_, ns_ = sent[i]
        ref = "entries[%d]; line %d; %s; %s%s%s" % (
            i, n, e.get("kind", ""), e["category"],
            "; generated by an AUTO rule of replacements_source.py" if e.get("generated") else "",
            "; provisional term (owner's call)" if e.get("owner") else "")
        r = base(next_rid(), "S95", S95J, ref, "edit", "applied", "scrubbed copy", "draft 5", n, H5[n],
                 e["old"], e["new"], os_, ns_, scope_of(orig, e["old"], os_))
        r["_key"] = ("S95", i)
        recs.append(r)
    for n, para in sorted(fills.items()):
        r = base(next_rid(), "S95", S95J, "fill_blank_lines[\"%d\"]; line %d (blank in draft 5)" % (n, n),
                 "edit", "applied", "scrubbed copy", "draft 5", n, H5[n] or Hs[n], "", para, "", para,
                 "paragraph")
        r["_key"] = ("S95fill", n)
        recs.append(r)
    # ---------- S96 stage 1 ----------
    R1 = json.load(open(SEM + S96J1, encoding="utf-8"))
    sc = texts["scrubbed copy"]
    ents1 = list(enumerate(R1["entries"]))
    rl = {int(k): v for k, v in R1.get("replace_lines", {}).items()}
    st1, sent1 = run_stage(sc, ents1, rl)
    report["stage 1 rebuild md5"] = md5("\n".join(st1))
    report["stage 1 md5 as expected"] = md5("\n".join(st1)) == STAGE1_MD5
    for i, e in ents1:
        n = e["line"]
        orig = sc[n - 1]
        os_, ns_ = sent1[i]
        ref = "entries[%d]; line %d; group %s; ref: %s%s" % (i, n, e["group"], e.get("ref", ""),
                                                            "; whole line" if e.get("whole_line") else "")
        r = base(next_rid(), "S96", S96J1, ref, "edit", "applied", "repaired copy", "scrubbed copy", n, Hs[n],
                 e["old"], e["new"], os_, ns_, scope_of(orig, e["old"], os_, e.get("whole_line")))
        r["_key"] = ("S96-1", i)
        r["_ref"] = e.get("ref", "")
        recs.append(r)
    for n, para in sorted(rl.items()):
        r = base(next_rid(), "S96", S96J1, "replace_lines[\"%d\"]; line %d (the dated note)" % (n, n), "edit",
                 "applied", "repaired copy", "scrubbed copy", n, Hs[n], sc[n - 1], para, sc[n - 1], para,
                 "paragraph")
        r["_key"] = ("S96-1rl", n)
        recs.append(r)
    # ---------- S96 stage 2 ----------
    R2 = json.load(open(SEM + S96J2, encoding="utf-8"))
    H1 = headings(st1)
    ents2 = list(enumerate(R2["entries"]))
    st2, sent2 = run_stage(st1, ents2)
    report["stage 2 equals repaired copy"] = st2 == texts["repaired copy"]
    for i, e in ents2:
        n = e["line"]
        orig = st1[n - 1]
        os_, ns_ = sent2[i]
        ref = "entries[%d]; line %d; group %s; ref: %s; how: %s" % (i, n, e["group"], e.get("ref", ""), e.get("how", ""))
        r = base(next_rid(), "S96", S96J2, ref, "edit", "applied", "repaired copy", STAGE1_NAME, n, H1[n],
                 e["old"], e["new"], os_, ns_, scope_of(orig, e["old"], os_))
        r["_key"] = ("S96-2", i)
        r["_ref"] = e.get("ref", "")
        r["_how"] = e.get("how", "")
        recs.append(r)
    # ---------- S96 stage 3 (log S97) ----------
    R3 = json.load(open(SEM + S96J3, encoding="utf-8"))
    rp = texts["repaired copy"]
    Hr = headings(rp)
    ents3 = list(enumerate(R3["entries"]))
    st3, sent3 = run_stage(rp, ents3)
    report["stage 3 equals latest text"] = st3 == texts["latest text"]
    for i, e in ents3:
        n = e["line"]
        orig = rp[n - 1]
        os_, ns_ = sent3[i]
        ref = "entries[%d]; line %d; group %s; ruling: %s" % (i, n, e["group"], e.get("ruling", ""))
        r = base(next_rid(), "S97", S96J3, ref, "edit", "applied", "latest text", "repaired copy", n, Hr[n],
                 e["old"], e["new"], os_, ns_, scope_of(orig, e["old"], os_))
        r["_key"] = ("S96-3", i)
        r["_ruling"] = e.get("ruling", "")
        recs.append(r)
    return recs, report, {"stage1": st1, **texts}
